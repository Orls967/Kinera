interface ComponentSeed {
  id: string;
  name: string;
  kind?: ComponentMetadata['kind'];
  category: string;
  layer: SystemLayerId;
  subsystemId: string;
  vehicleConfigurations: ConfigId[];
  description: string;
  primaryFunction: string;
  operatingPrinciple: string;
  inputs?: PortSpec[];
  outputs?: PortSpec[];
  specs?: Record<string, ValueWithUnit | string | null>;
  refs?: string[];
  animRefs?: string[];
}

function rel(
  id: string,
  sourceId: string,
  targetId: string,
  relationshipType: ComponentRelationship['relationshipType'],
  vehicleConfigurations: ConfigId[],
  transferredQuantity: string,
  bidirectional = false,
): ComponentRelationship {
  return {
    id,
    sourceId,
    targetId,
    relationshipType,
    vehicleConfigurations,
    transferredQuantity,
    bidirectional,
  };
}

